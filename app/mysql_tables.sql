CREATE TABLE IF NOT EXISTS users (
 id INT PRIMARY KEY AUTO_INCREMENT,
 name VARCHAR(100) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password VARCHAR(255) NOT NULL,
 role ENUM('candidate','recruiter','admin') NOT NULL,
 active TINYINT NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS jobs (
 id INT PRIMARY KEY AUTO_INCREMENT,
 title VARCHAR(200) NOT NULL,
 company VARCHAR(200) NOT NULL,
 location VARCHAR(200) NOT NULL,
 contract VARCHAR(200) NOT NULL,
 description TEXT NOT NULL,
 owner INT NOT NULL,
 status VARCHAR(20) NOT NULL DEFAULT 'pending',
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(owner) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS cvs (
 id INT PRIMARY KEY AUTO_INCREMENT,
 owner INT NOT NULL,
 path VARCHAR(255) NOT NULL,
 original VARCHAR(255) NOT NULL,
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(owner) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS applications (
 id INT PRIMARY KEY AUTO_INCREMENT,
 job INT NOT NULL,
 candidate INT NOT NULL,
 cv INT NOT NULL,
 status VARCHAR(30) NOT NULL DEFAULT 'En cours',
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY one_application(job,candidate),
 FOREIGN KEY(job) REFERENCES jobs(id),
 FOREIGN KEY(candidate) REFERENCES users(id),
 FOREIGN KEY(cv) REFERENCES cvs(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS events (
 id INT PRIMARY KEY AUTO_INCREMENT,
 actor INT NULL,
 event VARCHAR(100) NOT NULL,
 target VARCHAR(255),
 correlation VARCHAR(64) NOT NULL,
 created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(actor) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS cv_profiles (
 owner INT PRIMARY KEY,
 data LONGTEXT NOT NULL,
 FOREIGN KEY(owner) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
